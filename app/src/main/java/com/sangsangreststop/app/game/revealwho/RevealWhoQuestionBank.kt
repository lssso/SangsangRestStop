    /** 설정에 맞는 문제를 섞어서 한 판 분량만큼 고른다. */
    fun pick(settings: RevealWhoGameSettings, random: Random = Random.Default): List<RevealWhoQuestion> =
        all.filter { it.topic == settings.topic && it.level == settings.level }
            .shuffled(random)
            .take(settings.questionCount)

    private class TopicScope(
        private val topic: RevealWhoTopic,
        private val level: RevealWhoLevel,
        private val sink: MutableList<RevealWhoQuestion>,
    ) {
        fun q(answer: String, h1: String, h2: String, h3: String, h4: String, vararg synonyms: String) {
            sink += RevealWhoQuestion(answer, topic, level, listOf(h1, h2, h3, h4), synonyms.toList())
        }
    }

    private fun MutableList<RevealWhoQuestion>.topic(
        topic: RevealWhoTopic,
        level: RevealWhoLevel,
        block: TopicScope.() -> Unit,
    ) = TopicScope(topic, level, this).block()
}
